QString buildScript(const std::vector<Entity> &entities, const HullMap &hulls, const ExportOptions &opt,
                    int *entityCount, int *connectionCount) {
  const float scale = float(opt.unitScale);
  QStringList out;
  // No timestamp: an unchanged map must give the same bytes (no reimport).
  out << QStringLiteral("# Generated by the level editor from %1. Do not edit: export again instead.")
             .arg(opt.sourcePath.isEmpty() ? opt.mapName : QFileInfo(opt.sourcePath).fileName());
  out << QStringLiteral("# Runtime: addons/ghammer (enable the gHammer plugin, add an IOMap, set map_data to this "
                        "script).");
  out << QStringLiteral("extends RefCounted");
  out << QString();
  out << QStringLiteral("const VERSION = 1");
  out << QStringLiteral("const MAP_NAME = %1").arg(gdString(opt.mapName));
  out << QStringLiteral("## Editor world units to metres (positions and hulls below are already in metres).");
  out << QStringLiteral("const UNIT_SCALE = %1").arg(gdFloat(opt.unitScale));
  out << QString();
  out << QStringLiteral("## class, targetname, origin (m), angles (pitch, yaw, roll in degrees), props (snake_case),");
  out << QStringLiteral("## outputs [output, target, input, param, delay, times (-1 = unlimited)],");
  out << QStringLiteral("## hulls (brush entities: convex point sets relative to the origin, m).");
  out << QStringLiteral("const ENTITIES = [");

  QSet<QString> names, events;
  int ents = 0, conns = 0;
  for (const Entity &e: entities) {
    const EntityClass *cls = e.cls();
    if (!cls || !cls->io)
      continue;
    ++ents;
    if (!e.name.isEmpty())
      names.insert(e.name);
    if (e.classname == QLatin1String("logic_event")) {
      const QString ev = e.value(QStringLiteral("eventName")).toString();
      if (!ev.isEmpty())
        events.insert(ev);
    }
    QStringList props;
    QSet<QString> seen;
    for (const PropDef &p: cls->props) {
      props << QStringLiteral("%1: %2").arg(gdString(io::snake(p.key)), gdProp(p, e.value(p.key)));
      seen.insert(p.key);
    }
    for (auto it = e.props.constBegin(); it != e.props.constEnd(); ++it)
      if (!seen.contains(it.key()))
        props << QStringLiteral("%1: %2").arg(gdString(io::snake(it.key())), gdVariant(it.value()));
    QStringList outs;
    for (const auto &c: e.outputs) {
      if (c.disabled)
        continue;
      outs << QStringLiteral("[%1, %2, %3, %4, %5, %6]")
                  .arg(gdString(c.output), gdString(c.target), gdString(c.input), gdString(c.param),
                       gdFloat(std::max(0.0f, c.delay)))
                  .arg(c.times);
      ++conns;
    }
    QStringList hullList;
    if (const auto it = hulls.find(e.id); it != hulls.end())
      for (const auto &pts: it->second) {
        QStringList p;
        for (const glm::vec3 &v: pts)
          p << gdVec3((v - e.origin) * scale);
        hullList << QStringLiteral("[%1]").arg(p.join(QStringLiteral(", ")));
      }
    out << QStringLiteral("\t{");
    out << QStringLiteral("\t\t\"id\": %1, \"class\": %2, \"targetname\": %3,")
               .arg(e.id)
               .arg(gdString(e.classname), gdString(e.name));
    out << QStringLiteral("\t\t\"origin\": %1, \"angles\": %2,").arg(gdVec3(e.origin * scale), gdVec3(e.angles));
    out << QStringLiteral("\t\t\"props\": {%1},").arg(props.join(QStringLiteral(", ")));
    if (const auto it = opt.nodePaths.constFind(e.id); it != opt.nodePaths.constEnd())
      out << QStringLiteral("\t\t\"node\": %1,").arg(gdString(*it));
    out << QStringLiteral("\t\t\"outputs\": [%1],").arg(outs.join(QStringLiteral(", ")));
    out << QStringLiteral("\t\t\"hulls\": [%1],").arg(hullList.join(QStringLiteral(", ")));
    out << QStringLiteral("\t},");
  }
  out << QStringLiteral("]");
  out << QString();
  QStringList sortedNames(names.begin(), names.end());
  sortedNames.sort(Qt::CaseInsensitive);
  QStringList quoted;
  for (const auto &n: sortedNames)
    quoted << gdString(n);
  out << QStringLiteral("## Every targetname in the map (each is the group io_<lowercase name> at runtime).");
  out << QStringLiteral("const TARGETNAMES = [%1]").arg(quoted.join(QStringLiteral(", ")));
  QStringList sortedEvents(events.begin(), events.end());
  sortedEvents.sort(Qt::CaseInsensitive);
  quoted.clear();
  for (const auto &n: sortedEvents)
    quoted << gdString(n);
  out << QStringLiteral("## logic_event names: IO.event emits these, IO.raise() fires them.");
  out << QStringLiteral("const EVENTS = [%1]").arg(quoted.join(QStringLiteral(", ")));
  out << QString();
  if (entityCount)
    *entityCount = ents;
  if (connectionCount)
    *connectionCount = conns;
  return out.join('\n');
}

QString findProjectRoot(const QString &dir) {
  QDir d(dir);
  for (int i = 0; i < 64; ++i) {
    if (d.exists(QStringLiteral("project.godot")))
      return d.absolutePath();
    if (!d.cdUp())
      break;
  }
  return {};
}

int writeAddon(const QString &projectRoot, QString *error) {
  const QString src = QStringLiteral(":/ghammer/addons/ghammer");
  const QString dst = QDir(projectRoot).filePath(QStringLiteral("addons/ghammer"));
  int n = 0;
  QDirIterator it(src, QDir::Files, QDirIterator::Subdirectories);
  while (it.hasNext()) {
    const QString from = it.next();
    const QString rel = from.mid(src.size() + 1);
    const QString to = QDir(dst).filePath(rel);
    QFile in(from);
    if (!in.open(QIODevice::ReadOnly) || writeIfChanged(to, in.readAll(), error) < 0)
      return -1;
    ++n;
  }
  if (n == 0 && error)
    *error = QStringLiteral("The gHammer addon is not bundled in this build");
  return n;
}

