QString gdFloat(double v) {
  if (!std::isfinite(v))
    v = 0.0;
  // 7 significant digits round-trip floats (2.54, not 2.53999996).
  QString s = QString::number(v, 'g', 7);
  if (!s.contains('.') && !s.contains('e') && !s.contains("inf") && !s.contains("nan"))
    s += QStringLiteral(".0");
  return s;
}

QString gdVec3(const glm::vec3 &v) {
  return QStringLiteral("Vector3(%1, %2, %3)").arg(gdFloat(v.x), gdFloat(v.y), gdFloat(v.z));
}

QString gdColor(const QColor &c) {
  return QStringLiteral("Color(%1, %2, %3, %4)")
      .arg(gdFloat(c.redF()), gdFloat(c.greenF()), gdFloat(c.blueF()), gdFloat(c.alphaF()));
}

QString gdVariant(const QVariant &v) {
  switch (v.typeId()) {
    case QMetaType::Bool: return v.toBool() ? QStringLiteral("true") : QStringLiteral("false");
    case QMetaType::Int:
    case QMetaType::LongLong:
    case QMetaType::UInt: return QString::number(v.toLongLong());
    case QMetaType::Double:
    case QMetaType::Float: return gdFloat(v.toDouble());
    case QMetaType::QColor: return gdColor(v.value<QColor>());
    default: return gdString(v.toString());
  }
}

QString gdProp(const PropDef &p, const QVariant &v) {
  switch (p.type) {
    case PropType::Bool: return v.toBool() ? QStringLiteral("true") : QStringLiteral("false");
    case PropType::Int: return QString::number(v.toLongLong());
    case PropType::Float:
    case PropType::Angle: return gdFloat(v.toDouble());
    case PropType::Color: {
      const QColor c = v.typeId() == QMetaType::QColor ? v.value<QColor>() : QColor(v.toString());
      return gdColor(c.isValid() ? c : QColor(Qt::white));
    }
    default: return gdString(v.toString());
  }
}

